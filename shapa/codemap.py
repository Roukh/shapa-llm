def _embed_missing(conn, deadline: float, clock) -> int:
    """Embed the terms of files that have no vector yet (the ``[semantic]`` extra)."""
    stamp = conn.execute("SELECT value FROM meta WHERE key = 'model'").fetchone()
    if stamp and stamp[0] != embed.model_name():
        conn.execute("UPDATE files SET vec = NULL")
    rows = conn.execute(
        "SELECT id, terms FROM files WHERE vec IS NULL AND status = 'ok' AND terms != ''").fetchall()
    if not rows or clock() >= deadline or not embed.available():
        return 0
    n = 0
    conn.execute("BEGIN")
    for i in range(0, len(rows), 256):
        if clock() >= deadline:
            break
        chunk = rows[i:i + 256]
        mat = embed.embed_many([t for _id, t in chunk])
        for (fid, _t), v in zip(chunk, mat):
            conn.execute("UPDATE files SET vec = ? WHERE id = ?",
                         (array("f", [float(x) for x in v]).tobytes(), fid))
            n += 1
    conn.execute("INSERT OR REPLACE INTO meta VALUES ('model', ?)", (embed.model_name(),))
    conn.execute("COMMIT")
    return n


# --- reading the map -------------------------------------------------------------------------------

@dataclass
class FileRec:
    id: int
    path: str
    lang: str
    size: int
    status: str


class Graph:
    """A read-only view of a code map. Opening one never writes (no file is created)."""

    def __init__(self, conn: sqlite3.Connection, repo: Path):
        self.conn = conn
        self.repo = repo
        self._files: dict[str, FileRec] | None = None
        self._by_id: dict[int, FileRec] | None = None
        self._base: dict[str, list[str]] | None = None

    def close(self) -> None:
        self.conn.close()

    # files
    def files(self) -> dict[str, FileRec]:
        if self._files is None:
            self._files = {p: FileRec(i, p, lg, sz, stt) for i, p, lg, sz, stt in self.conn.execute(
                "SELECT id, path, lang, size, status FROM files")}
            self._by_id = {f.id: f for f in self._files.values()}
        return self._files

    def by_id(self, fid: int) -> FileRec | None:
        self.files()
        return self._by_id.get(fid) if self._by_id else None

    def meta(self, key: str) -> str | None:
        r = self.conn.execute("SELECT value FROM meta WHERE key = ?", (key,)).fetchone()
        return r[0] if r else None

    def total_bytes(self) -> int:
        return sum(f.size for f in self.files().values())

    def resolve_mention(self, mention: str) -> list[str]:
        """Paths a text's file mention can mean: the exact path, else every file whose path
        ends with it (at most three, so an ambiguous bare name stays modest)."""
        files = self.files()
        m = mention.strip().lstrip("./")
        if m in files:
            return [m]
        if self._base is None:
            self._base = defaultdict(list)
            for p in files:
                self._base[p.rsplit("/", 1)[-1]].append(p)
        tail = [p for p in self._base.get(m.rsplit("/", 1)[-1], ()) if p == m or p.endswith("/" + m)]
        return sorted(tail)[:3]

    # symbols
    def symbols_named(self, name: str, limit: int = 8) -> list[tuple[str, str, str]]:
        """``(path, qual, kind)`` of the functions and classes called *name* (also the
        ``name`` of a method ``Class.name``), at most *limit*."""
        out = []
        for fid, qual, kind in self.conn.execute(
                "SELECT fid, qual, kind FROM symbols WHERE name = ? LIMIT ?", (name, limit)):
            f = self.by_id(fid)
            if f is not None:
                out.append((f.path, qual, kind))
        return out

    def symbols_of(self, path: str) -> list[tuple[str, str, int]]:
        f = self.files().get(path)
        if f is None:
            return []
        return [(q, k, ln) for q, k, ln in self.conn.execute(
            "SELECT qual, kind, line FROM symbols WHERE fid = ? ORDER BY line", (f.id,))]

    # edges
    def _edges(self, sql: str, args: tuple) -> list[tuple[str, str, str, float]]:
        out = []
        for other, ssym, dsym, w in self.conn.execute(sql, args):
            f = self.by_id(other)
            if f is not None:
                out.append((f.path, ssym, dsym, w))
        return out

    def importers(self, path: str) -> list[tuple[str, str, float]]:
        """``(file, imported symbol, weight)`` of the files that import *path*."""
        f = self.files().get(path)
        if f is None:
            return []
        return [(p, ds, w) for p, _s, ds, w in self._edges(
            "SELECT src, src_sym, dst_sym, w FROM edges WHERE dst = ? AND kind = 'imports' LIMIT ?",
            (f.id, FANOUT_CAP * 4))]

    def imports_of(self, path: str) -> list[tuple[str, float]]:
        f = self.files().get(path)
        if f is None:
            return []
        return [(p, w) for p, _s, _d, w in self._edges(
            "SELECT dst, src_sym, dst_sym, w FROM edges WHERE src = ? AND kind = 'imports' LIMIT ?",
            (f.id, FANOUT_CAP * 4))]

    def callers(self, path: str, qual: str | None = None) -> list[tuple[str, str, str, float]]:
        """``(file, calling function, called function, weight)`` of calls into *path* (into the
        function *qual* when given; into a class also counts its methods)."""
        f = self.files().get(path)
        if f is None:
            return []
        if qual is None:
            return self._edges("SELECT src, src_sym, dst_sym, w FROM edges WHERE dst = ? AND kind = 'calls' "
                               "LIMIT ?", (f.id, FANOUT_CAP * 4))
        return self._edges(
            "SELECT src, src_sym, dst_sym, w FROM edges WHERE dst = ? AND kind = 'calls' "
            "AND (dst_sym = ? OR dst_sym LIKE ? ESCAPE '\\') LIMIT ?",
            (f.id, qual, qual.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + ".%",
             FANOUT_CAP * 4))

    def callees(self, path: str, qual: str | None = None) -> list[tuple[str, str, str, float]]:
        """``(file, calling function, called function, weight)`` of calls out of *path*."""
        f = self.files().get(path)
        if f is None:
            return []
        if qual is None:
            return self._edges("SELECT dst, src_sym, dst_sym, w FROM edges WHERE src = ? AND kind = 'calls' "
                               "LIMIT ?", (f.id, FANOUT_CAP * 4))
        return self._edges(
            "SELECT dst, src_sym, dst_sym, w FROM edges WHERE src = ? AND kind = 'calls' AND src_sym = ? "
            "LIMIT ?", (f.id, qual, FANOUT_CAP * 4))

    # retrieval
    def lexical(self, query_terms: list[str], limit: int = 40) -> dict[str, float]:
        """BM25 over the files' terms: FTS5 when the index has it, else the shared hand-rolled BM25."""
        terms = sorted({t for t in query_terms if re.fullmatch(r"[a-z0-9]{2,40}", t)})[:40]
        if not terms:
            return {}
        has_fts = self.conn.execute(
            "SELECT 1 FROM sqlite_master WHERE name = 'file_terms'").fetchone() is not None
        if has_fts:
            match = " OR ".join(f'"{t}"' for t in terms)
            try:
                rows = self.conn.execute(
                    "SELECT f.path, -bm25(file_terms) FROM file_terms JOIN files f ON f.id = file_terms.rowid "
                    "WHERE file_terms MATCH ? ORDER BY bm25(file_terms) LIMIT ?", (match, limit)).fetchall()
            except sqlite3.OperationalError:
                rows = []
            return {p: float(s) for p, s in rows if s > 0}
        from shapa.bm25 import bm25_scores

        docs = {p: t.split() for p, t in self.conn.execute(
            "SELECT path, terms FROM files WHERE status = 'ok'")}
        scores = bm25_scores(" ".join(terms), docs)
        top = sorted((kv for kv in scores.items() if kv[1] > 0), key=lambda kv: (-kv[1], kv[0]))[:limit]
        return dict(top)

    def term_overlap(self, path: str, query_terms: list[str]) -> int:
        r = self.conn.execute("SELECT terms FROM files WHERE path = ?", (path,)).fetchone()
        return len(set(r[0].split()) & set(query_terms)) if r else 0

    def vectors(self, query: str, limit: int = 40) -> dict[str, float]:
        """Cosine of *query* against the stored file vectors (empty without the ``[semantic]`` extra
        or when the map holds no vector)."""
        if not embed.installed():
            return {}
        rows = self.conn.execute("SELECT path, vec FROM files WHERE vec IS NOT NULL").fetchall()
        if not rows or not embed.available():
            return {}
        stamp = self.meta("model")
        if stamp and stamp != embed.model_name():
            return {}
        q = embed.embed_one(query)
        out: dict[str, float] = {}
        for p, blob in rows:
            v = array("f")
            v.frombytes(blob)
            if len(v) == len(q):
                s = embed.cosine(q, list(v))
                if s > 0:
                    out[p] = s
        return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0]))[:limit])


def open_graph(wiki_root, *, repo=None) -> Graph | None:
    """The code map of *wiki_root*'s checkout, read-only; ``None`` when there is none, it is
    unreadable, or it was built for another checkout (a copied index). Never writes."""
    path = index_path(wiki_root)
    if not path.is_file():
        return None
    try:
        # a short timeout: a build holding the write lock must never stall a session start
        conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=0.5)
        conn.execute("PRAGMA query_only = ON")
        row = conn.execute("SELECT value FROM meta WHERE key = 'schema'").fetchone()
        root = conn.execute("SELECT value FROM meta WHERE key = 'root'").fetchone()
        want = str(Path(repo).resolve()) if repo else str(checkout_root(wiki_root))
        if row is None or row[0] != SCHEMA or root is None or root[0] != want:
            conn.close()
            return None
        return Graph(conn, Path(want))
    except (sqlite3.DatabaseError, OSError):
        return None
