MAX_ENTRIES = 400_000   # directory entries looked at, code or not
MAX_DEPTH = 40
MAX_SYMBOLS_PER_FILE = 400
MAX_CALLS_PER_FILE = 800
MAX_IMPORTS_PER_FILE = 300
MAX_TERMS_CHARS = 2000
FANOUT_CAP = 60  # call/import neighbours kept per node

_IDENT = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]{0,99}\Z")

# --- credential files: never read, recorded or printed ---------------------------------

_SECRET_NAMES = frozenset({
    ".envrc", ".dev.vars", ".npmrc", ".netrc", ".pgpass", ".git-credentials", ".pypirc",
    "service.json", "auth.json", "opencode.db", "opencode.db-wal", "opencode.db-shm",
    "credentials", "credentials.json", "secrets.json", "secrets.yml", "secrets.yaml",
    "kubeconfig", "id_rsa", "id_dsa", "id_ecdsa", "id_ed25519"})
_SECRET_SUFFIXES = (".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".kdbx", ".gpg", ".ppk")
_TEMPLATE_SUFFIXES = (".example", ".sample", ".template", ".dist")


def is_secret_name(name: str) -> bool:
    """True for a file name that holds credentials (``.env`` and its variants but
    not the ``.example``/``.sample``/``.template``/``.dist`` templates, ``.envrc``,
    ``.dev.vars``, shapa's device token ``remote.token*``, private keys and
    keystores, OpenCode's ``auth.json``/``service.json``/``opencode.db``)."""
    n = name.lower()
    if n in _SECRET_NAMES or n.startswith(("remote.token", "id_rsa", "id_ed25519", "id_ecdsa")):
        return True
    if n.startswith(".env") and not n.endswith(_TEMPLATE_SUFFIXES):
        return True
    return n.endswith(_SECRET_SUFFIXES)


def is_secret_path(rel: str) -> bool:
    """:func:`is_secret_name` for any component of *rel*, and the credential folders."""
    return any(is_secret_name(p) or p.lower() in (".ssh", ".aws", ".kube", ".gnupg", ".gcloud")
               for p in rel.replace("\\", "/").split("/"))


def safe_path(rel: str) -> bool:
    """A path that may be stored and printed: short, no control, format or line-separator
    character (a file name cannot add a line or a tag to a session start), no markup
    character and nothing credential-like."""
    if not rel or len(rel) > MAX_PATH_CHARS or rel.startswith(("/", "../")) or "/../" in rel:
        return False
    if any(unicodedata.category(c) in ("Cc", "Cf", "Zl", "Zp") or c in "<>`|" for c in rel):
        return False
    return not is_secret_path(rel)


# --- where it lives -----------------------------------------------------------------------

def checkout_root(wiki_root) -> Path:
    """The checkout a wiki belongs to: the nearest ancestor holding ``.git`` (a file in
    a linked worktree), else the wiki's parent folder."""
    start = Path(wiki_root).resolve()
    for d in (start, *start.parents):
        if (d / ".git").exists():
            return d
    return start.parent


def index_path(wiki_root) -> Path:
    return Path(wiki_root) / INDEX_FILENAME


# --- tokens -------------------------------------------------------------------------------

_CAMEL = re.compile(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+")


def tokens(text: str) -> list[str]:
    """Lowercase search tokens of *text*: identifiers split at ``_``, ``-``, ``.``, ``/``
    and camelCase humps, stop words and one-letter pieces dropped."""
    out: list[str] = []
    for chunk in re.findall(r"[A-Za-z][A-Za-z0-9]*", text or ""):
        for piece in _CAMEL.findall(chunk):
            p = piece.lower()
            if len(p) >= 2 and p not in _STOP:
                out.append(p)
    return out


def _terms(path: str, names: list[str], docs: list[str]) -> str:
    seen: dict[str, None] = {}
    for src in (path, " ".join(names), " ".join(docs)):
        for t in tokens(src):
            seen.setdefault(t, None)
    out = " ".join(seen)
    return out[:MAX_TERMS_CHARS].rsplit(" ", 1)[0] if len(out) > MAX_TERMS_CHARS else out


# --- extraction: Python ---------------------------------------------------------------------

@dataclass
class Facts:
    symbols: list = field(default_factory=list)   # (qual, name, kind, line)
    imports: list = field(default_factory=list)   # (mod, name, alias, level)
    calls: list = field(default_factory=list)     # (caller, qualifier, name)
    docs: list = field(default_factory=list)
    status: str = "ok"


def _py_target(func) -> tuple[str, str] | None:
    if isinstance(func, ast.Name):
        return "", func.id
    if isinstance(func, ast.Attribute):
        parts: list[str] = []
        n = func
        while isinstance(n, ast.Attribute) and len(parts) < 12:
            parts.append(n.attr)
            n = n.value
        if isinstance(n, ast.Name):
            parts.append(n.id)
            parts.reverse()
            return ".".join(parts[:-1]), parts[-1]
        return "?", func.attr
    return None


def _py_facts(text: str) -> Facts:
    f = Facts()
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError, OverflowError):
        f.status = "error"
        return f
    calls: set[tuple[str, str, str]] = set()
    doc = ast.get_docstring(tree)
    if doc:
        f.docs.append(doc.splitlines()[0][:120])
    stack: list[tuple[ast.AST, str, str]] = [(tree, "", "")]  # node, caller, enclosing class
    while stack:
        node, caller, cls = stack.pop()
        for child in ast.iter_child_nodes(node):
            c_caller, c_cls = caller, cls
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not caller or (cls and caller == cls):  # a def of the module or of a class
                    qual = f"{cls}.{child.name}" if cls else child.name
                    if _IDENT.match(child.name) and len(f.symbols) < MAX_SYMBOLS_PER_FILE:
                        f.symbols.append((qual, child.name, "method" if cls else "function",
                                          child.lineno))
                        d = ast.get_docstring(child)
                        if d and len(f.docs) < 12:
                            f.docs.append(d.splitlines()[0][:120])
                    c_caller, c_cls = qual, cls
            elif isinstance(child, ast.ClassDef):
                if not caller and _IDENT.match(child.name):
                    if len(f.symbols) < MAX_SYMBOLS_PER_FILE:
                        f.symbols.append((child.name, child.name, "class", child.lineno))
                    c_caller, c_cls = child.name, child.name
            elif isinstance(child, ast.Call):
                t = _py_target(child.func)
                if t and _IDENT.match(t[1]) and len(calls) < MAX_CALLS_PER_FILE:
                    calls.add((caller, t[0], t[1]))
            elif isinstance(child, ast.Import):
                for a in child.names:
                    if len(f.imports) < MAX_IMPORTS_PER_FILE:
                        f.imports.append((a.name, "", a.asname or "", 0))
            elif isinstance(child, ast.ImportFrom):
                for a in child.names:
                    if len(f.imports) < MAX_IMPORTS_PER_FILE:
                        f.imports.append((child.module or "", a.name, a.asname or "", child.level or 0))
            stack.append((child, c_caller, c_cls))
    f.calls = sorted(calls)
    return f


# --- extraction: JavaScript and TypeScript ----------------------------------------------------

_JS_SPECIAL = re.compile(r"""["'`/]""")
_JS_STRING = {'"': re.compile(r'(?:\\.|[^"\\\n])*'), "'": re.compile(r"(?:\\.|[^'\\\n])*"),
              "`": re.compile(r"(?:\\.|[^`\\])*", re.S)}
_JS_IMPORT = re.compile(
    r"""\bimport\s+(?:type\s+)?([\w$\s,{}*]{1,400}?)\s+from\s*['"]([^'"\n]{1,200})['"]""")
_JS_IMPORT_BARE = re.compile(r"""\bimport\s*['"]([^'"\n]{1,200})['"]""")
_JS_REEXPORT = re.compile(r"""\bexport\s+(?:type\s+)?(\*|\{[^}]{0,2000}\})\s*(?:as\s+\w+\s*)?from\s*['"]([^'"\n]{1,200})['"]""")
_JS_REQUIRE = re.compile(
    r"""(?:\b(?:const|let|var)\s+(\{[^}]{0,2000}\}|[\w$]+)\s*=\s*)?\brequire\(\s*['"]([^'"\n]{1,200})['"]\s*\)""")
_JS_DYNAMIC = re.compile(r"""\bimport\(\s*['"]([^'"\n]{1,200})['"]\s*\)""")
_JS_FUNC = re.compile(r"""\b(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)""")
_JS_CLASS = re.compile(r"""\b(?:export\s+)?(?:default\s+)?(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)""")
_JS_ARROW = re.compile(
    r"""\b(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*(?::[^=\n]{1,120})?=\s*"""
    r"""(?:async\s*)?(?:function\b|\([^)]{0,300}\)\s*(?::[^=\n]{1,120})?=>|[A-Za-z_$][\w$]*\s*=>)""")
_JS_TYPE = re.compile(r"""\bexport\s+(?:declare\s+)?(?:interface|type|enum|const)\s+([A-Za-z_$][\w$]*)""")
_JS_CALL = re.compile(r"""(?<![\w$.])([A-Za-z_$][\w$]*)\s*\(""")
_JS_MEMBER = re.compile(r"""(?<![\w$.])([A-Za-z_$][\w$]*)\.([A-Za-z_$][\w$]*)\s*\(""")
_JS_JSX = re.compile(r"""<([A-Z][\w$]*)""")
_JS_KEYWORDS = frozenset({"if", "for", "while", "switch", "catch", "function", "return", "typeof",
                          "new", "await", "async", "super", "import", "require", "constructor",
                          "else", "do", "with", "void", "delete", "in", "of", "yield", "throw"})


def _js_names(clause: str) -> list[tuple[str, str]]:
    """``(imported name, local alias)`` pairs of an import clause."""
    out: list[tuple[str, str]] = []
    clause = clause.strip()
    m = re.search(r"\{([^}]*)\}", clause)
    if m:
        for part in m.group(1).split(","):
            bits = re.split(r"\s+as\s+", part.strip().removeprefix("type "))
            if bits and _IDENT.match(bits[0]):
                out.append((bits[0], bits[-1] if _IDENT.match(bits[-1]) else bits[0]))
        clause = clause.replace(m.group(0), " ")
    ns = re.search(r"\*\s*as\s+([A-Za-z_$][\w$]*)", clause)
    if ns:
        out.append(("*", ns.group(1)))
        clause = clause.replace(ns.group(0), " ")
    for part in clause.split(","):
        part = part.strip()
        if part and _IDENT.match(part):
            out.append(("default", part))
    return out


def _js_strip(text: str) -> str:
    """*text* without its comments (strings kept: import specs live in them). One pass, linear:
    an unterminated string, template or block comment ends at the line or the file, never
    sends the scan back over the same text."""
    out: list[str] = []
    i, n = 0, len(text)
    while i < n:
        m = _JS_SPECIAL.search(text, i)
        if m is None:
            out.append(text[i:])
            break
        j = m.start()
        out.append(text[i:j])
        c = text[j]
        if c == "/":
            nxt = text[j + 1:j + 2]
            if nxt == "/":
                end = text.find("\n", j)
                i = n if end < 0 else end
                out.append(" ")
            elif nxt == "*":
                end = text.find("*/", j + 2)
                i = n if end < 0 else end + 2
                out.append(" ")
            else:
                out.append("/")
                i = j + 1
        else:
            k = _JS_STRING[c].match(text, j + 1).end()
            if k < n and text[k] == c:
                k += 1
            out.append(text[j:k])
            i = k
    return "".join(out)


def _js_facts(text: str) -> Facts:
    f = Facts()
    text = _js_strip(text)
    nl = [m.start() for m in re.finditer("\n", text)]
    spans: list[tuple[int, str, str, str]] = []  # offset, qual, name, kind
    for rx, kind in ((_JS_FUNC, "function"), (_JS_CLASS, "class"), (_JS_ARROW, "function"),
                     (_JS_TYPE, "type")):
        for m in rx.finditer(text):
            if _IDENT.match(m.group(1)):
                spans.append((m.start(), m.group(1), m.group(1), kind))
    spans.sort()
    seen: set[str] = set()
    for off, qual, name, kind in spans:
        if qual not in seen and len(f.symbols) < MAX_SYMBOLS_PER_FILE:
            seen.add(qual)
            f.symbols.append((qual, name, kind, bisect.bisect_right(nl, off) + 1))
    for m in _JS_IMPORT.finditer(text):
        for name, alias in _js_names(m.group(1)):
            if len(f.imports) < MAX_IMPORTS_PER_FILE:
                f.imports.append((m.group(2), name, alias, 0))
    for m in _JS_IMPORT_BARE.finditer(text):
        f.imports.append((m.group(1), "", "", 0))
    for m in _JS_REEXPORT.finditer(text):
        names = _js_names(m.group(1)) if m.group(1) != "*" else []
        for name, _alias in names or [("", "")]:
            f.imports.append((m.group(2), name, "", 0))
    for m in _JS_REQUIRE.finditer(text):
        binding = m.group(1) or ""
        if binding.startswith("{"):
            for name, alias in _js_names(binding):
                f.imports.append((m.group(2), name, alias, 0))
        elif binding:
            f.imports.append((m.group(2), "*", binding, 0))
        else:
            f.imports.append((m.group(2), "", "", 0))
    for m in _JS_DYNAMIC.finditer(text):
        f.imports.append((m.group(1), "", "", 0))
    f.imports = f.imports[:MAX_IMPORTS_PER_FILE]
    starts = [s[0] for s in spans]
    quals = [s[1] for s in spans]
    calls: set[tuple[str, str, str]] = set()

    def caller_at(pos: int) -> str:
        i = bisect.bisect_right(starts, pos) - 1
        return quals[i] if i >= 0 else ""

    for m in _JS_MEMBER.finditer(text):
        if len(calls) < MAX_CALLS_PER_FILE:
            calls.add((caller_at(m.start()), m.group(1), m.group(2)))
    for m in _JS_CALL.finditer(text):
        if m.group(1) not in _JS_KEYWORDS and len(calls) < MAX_CALLS_PER_FILE:
            calls.add((caller_at(m.start()), "", m.group(1)))
    for m in _JS_JSX.finditer(text):
        if len(calls) < MAX_CALLS_PER_FILE:
            calls.add((caller_at(m.start()), "", m.group(1)))
    f.calls = sorted(calls)
    return f


def extract(lang: str, text: str) -> Facts:
    try:
        return _py_facts(text) if lang == "py" else _js_facts(text)
    except (RecursionError, MemoryError, re.error):
        return Facts(status="error")


# --- the walk -----------------------------------------------------------------------------------

@dataclass
class Scan:
    files: list = field(default_factory=list)   # (rel, size, mtime_ns)
    truncated: bool = False
    skipped_large: int = 0
    skipped_unsafe: int = 0


def scan(root: Path, max_files: int = MAX_FILES) -> Scan:
    """The code files under *root* that may be indexed. Never follows a symlink, never
    enters a hidden, vendored, generated or nested-checkout folder, never opens a file."""
    out = Scan()
    root = Path(root)
    examined = 0
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        here = Path(dirpath)
        examined += len(dirnames) + len(filenames)
        if examined > MAX_ENTRIES:  # a tree of millions of non-code entries is bounded too
            out.truncated = True
            return out
        if len(here.relative_to(root).parts) >= MAX_DEPTH:
            dirnames[:] = []
        keep = []
        for d in sorted(dirnames):
            low = d.lower()
            if d.startswith(".") or low in SKIP_DIRS or low.endswith(".egg-info") or is_secret_name(d):
                continue
            if (here / d / ".git").exists():  # a nested checkout or submodule is not this repo's code
                continue
            keep.append(d)
        dirnames[:] = keep
        rel_dir = here.relative_to(root).as_posix()
        for name in sorted(filenames):
            ext = os.path.splitext(name)[1].lower()
            if ext not in LANG or name.lower().endswith(SKIP_SUFFIXES) or is_secret_name(name):
                continue
            rel = name if rel_dir == "." else f"{rel_dir}/{name}"
            if not safe_path(rel):
                out.skipped_unsafe += 1
                continue
            try:
                st = os.lstat(here / name)
            except OSError:
                continue
            if not stat.S_ISREG(st.st_mode):  # a symlink, a fifo, a socket, a device
                continue
            if st.st_size > MAX_FILE_BYTES:
                out.skipped_large += 1
                continue
            if len(out.files) >= max_files:
                out.truncated = True
                return out
            out.files.append((rel, st.st_size, st.st_mtime_ns))
    return out


def _read(path: Path) -> bytes | None:
    """The file's bytes, opened without following a symlink and without blocking on a
    special file; ``None`` when it vanished, changed type or grew past the cap."""
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0) \
        | getattr(os, "O_CLOEXEC", 0)
    try:
        if os.path.realpath(path) != os.fspath(path):  # a directory swapped for a link since the walk
            return None
        fd = os.open(path, flags)
    except OSError:
        return None
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_FILE_BYTES:
            return None
        with os.fdopen(fd, "rb", closefd=False) as fh:
            data = fh.read(MAX_FILE_BYTES + 1)
        return None if len(data) > MAX_FILE_BYTES else data
    except OSError:
        return None
    finally:
        os.close(fd)


