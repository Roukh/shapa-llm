_DDL = """
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS files (
    id INTEGER PRIMARY KEY, path TEXT NOT NULL UNIQUE, lang TEXT NOT NULL, size INTEGER NOT NULL,
    mtime_ns INTEGER NOT NULL, hash TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'ok',
    terms TEXT NOT NULL DEFAULT '', vec BLOB);
CREATE TABLE IF NOT EXISTS symbols (fid INTEGER NOT NULL, qual TEXT NOT NULL, name TEXT NOT NULL,
    kind TEXT NOT NULL, line INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS symbols_fid ON symbols(fid);
CREATE INDEX IF NOT EXISTS symbols_name ON symbols(name);
CREATE TABLE IF NOT EXISTS imports (fid INTEGER NOT NULL, mod TEXT NOT NULL, name TEXT NOT NULL,
    alias TEXT NOT NULL, level INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS imports_fid ON imports(fid);
CREATE TABLE IF NOT EXISTS calls (fid INTEGER NOT NULL, caller TEXT NOT NULL, qual TEXT NOT NULL,
    name TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS calls_fid ON calls(fid);
CREATE TABLE IF NOT EXISTS edges (kind TEXT NOT NULL, src INTEGER NOT NULL, dst INTEGER NOT NULL,
    src_sym TEXT NOT NULL, dst_sym TEXT NOT NULL, w REAL NOT NULL);
CREATE INDEX IF NOT EXISTS edges_dst ON edges(dst, kind);
CREATE INDEX IF NOT EXISTS edges_src ON edges(src, kind);
"""
_FTS = "CREATE VIRTUAL TABLE IF NOT EXISTS file_terms USING fts5(terms)"


def _open_rw(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(str(path), timeout=10, isolation_level=None)
    try:
        conn.execute("PRAGMA synchronous = OFF")  # derived data: a crash just rebuilds
        conn.execute("PRAGMA journal_mode = MEMORY")
        conn.executescript(_DDL)
        row = conn.execute("SELECT value FROM meta WHERE key = 'schema'").fetchone()
        if row is None:
            conn.execute("INSERT INTO meta VALUES ('schema', ?)", (SCHEMA,))
        elif row[0] != SCHEMA:
            raise sqlite3.DatabaseError("code index schema mismatch")
        if store.fts5_available():
            conn.execute(_FTS)
        return conn
    except sqlite3.DatabaseError:
        conn.close()
        raise


def _fresh_db(path: Path) -> sqlite3.Connection:
    """Open the index, deleting and recreating it when it is corrupt or from another schema."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        return _open_rw(path)
    except sqlite3.DatabaseError:
        for suffix in ("", "-journal", "-wal", "-shm"):
            try:
                os.unlink(str(path) + suffix)
            except OSError:
                pass
        return _open_rw(path)


@dataclass
class BuildStats:
    files: int = 0        # code files in the map
    parsed: int = 0       # read and parsed this run
    reused: int = 0       # unchanged since the last run
    removed: int = 0      # gone from disk, dropped from the map
    skipped: int = 0      # generated, unparsable, too large or unsafe
    symbols: int = 0
    imports: int = 0      # import edges
    calls: int = 0        # call edges
    truncated: bool = False   # the file cap was reached
    partial: bool = False     # the time budget ran out; run again to continue
    seconds: float = 0.0
    vectors: int = 0

    def as_dict(self) -> dict:
        return dict(self.__dict__)


def _generated(head: bytes) -> bool:
    return any(m in head[:600] for m in GENERATED_MARKERS)


def build(wiki_root, *, root=None, seconds: float = BUILD_SECONDS, max_files: int = MAX_FILES,
          clock=time.monotonic, vectors: bool = True) -> BuildStats:
    """Create or refresh the code map of the checkout *wiki_root* belongs to (or *root*).
    Incremental: a file is re-read only when its mtime or size changed, and re-parsed only
    when its hash did. Files that vanished are dropped. Stops parsing after *seconds*."""
    t0 = clock()
    deadline = t0 + max(0.0, seconds)
    repo = Path(root).resolve() if root else checkout_root(wiki_root)
    st = BuildStats()
    found = scan(repo, max_files)
    st.truncated = found.truncated
    st.skipped = found.skipped_large + found.skipped_unsafe
    conn = _fresh_db(index_path(wiki_root))
    try:
        old_root = conn.execute("SELECT value FROM meta WHERE key = 'root'").fetchone()
        if old_root and old_root[0] != str(repo):  # an index copied from another checkout
            conn.close()
            os.unlink(index_path(wiki_root))
            conn = _fresh_db(index_path(wiki_root))
        known = {p: (fid, mt, sz, h) for fid, p, mt, sz, h in conn.execute(
            "SELECT id, path, mtime_ns, size, hash FROM files")}
        seen = {rel for rel, _s, _m in found.files}
        changed = False
        conn.execute("BEGIN")
        gone = [p for p in known if p not in seen]
        for p in gone:
            _drop(conn, known[p][0])
            changed = True
        st.removed = len(gone)
        done = 0
        for rel, size, mtime in found.files:
            prior = known.get(rel)
            if prior and prior[1] == mtime and prior[2] == size:
                st.reused += 1
                continue
            if clock() >= deadline:
                st.partial = True
                continue
            data = _read(repo / rel)
            if data is None:
                st.skipped += 1
                continue
            digest = hashlib.sha1(data).hexdigest()
            if prior and prior[3] == digest:
                conn.execute("UPDATE files SET mtime_ns = ?, size = ? WHERE id = ?",
                             (mtime, size, prior[0]))
                st.reused += 1
                continue
            lang = LANG[os.path.splitext(rel)[1].lower()]
            if _generated(data):
                facts = Facts(status="generated")
            else:
                facts = extract(lang, data.decode("utf-8", errors="replace"))
            _store_file(conn, prior[0] if prior else None, rel, lang, size, mtime, digest, facts)
            st.parsed += 1
            changed = True
            done += 1
            if done % 250 == 0:
                conn.execute("COMMIT")
                conn.execute("BEGIN")
        conn.execute("COMMIT")
        if changed or conn.execute("SELECT COUNT(*) FROM edges").fetchone()[0] == 0:
            conn.execute("BEGIN")
            _resolve(conn)
            conn.execute("COMMIT")
        if vectors and embed.installed():
            st.vectors = _embed_missing(conn, deadline, clock)
        conn.execute("BEGIN")
        for k, v in (("root", str(repo)), ("built_at", str(int(time.time()))),
                     ("partial", "1" if st.partial else "0"),
                     ("truncated", "1" if st.truncated else "0")):
            conn.execute("INSERT OR REPLACE INTO meta VALUES (?, ?)", (k, v))
        conn.execute("COMMIT")
        st.files = conn.execute("SELECT COUNT(*) FROM files").fetchone()[0]
        st.skipped += conn.execute("SELECT COUNT(*) FROM files WHERE status != 'ok'").fetchone()[0]
        st.symbols = conn.execute("SELECT COUNT(*) FROM symbols").fetchone()[0]
        st.imports = conn.execute("SELECT COUNT(*) FROM edges WHERE kind = 'imports'").fetchone()[0]
        st.calls = conn.execute("SELECT COUNT(*) FROM edges WHERE kind = 'calls'").fetchone()[0]
    finally:
        conn.close()
    st.seconds = clock() - t0
    return st


def _drop(conn, fid: int) -> None:
    for table in ("symbols", "imports", "calls"):
        conn.execute(f"DELETE FROM {table} WHERE fid = ?", (fid,))
    conn.execute("DELETE FROM edges WHERE src = ? OR dst = ?", (fid, fid))
    if store.fts5_available():
        try:
            conn.execute("DELETE FROM file_terms WHERE rowid = ?", (fid,))
        except sqlite3.OperationalError:
            pass
    conn.execute("DELETE FROM files WHERE id = ?", (fid,))


def _store_file(conn, fid, rel, lang, size, mtime, digest, facts: Facts) -> None:
    if fid is not None:
        _drop(conn, fid)
    names = [s[1] for s in facts.symbols]
    docs = [redact(d) for d in facts.docs]
    terms = _terms(rel, names, docs)
    cur = conn.execute(
        "INSERT INTO files (path, lang, size, mtime_ns, hash, status, terms) VALUES (?,?,?,?,?,?,?)",
        (rel, lang, size, mtime, digest, facts.status, terms))
    fid = cur.lastrowid
    conn.executemany("INSERT INTO symbols VALUES (?,?,?,?,?)",
                     [(fid, q, n, k, ln) for q, n, k, ln in facts.symbols])
    conn.executemany("INSERT INTO imports VALUES (?,?,?,?,?)",
                     [(fid, m, n, a, lv) for m, n, a, lv in facts.imports])
    conn.executemany("INSERT INTO calls VALUES (?,?,?,?)",
                     [(fid, c, q, n) for c, q, n in facts.calls])
    if store.fts5_available() and facts.status == "ok":
        try:
            conn.execute("INSERT INTO file_terms(rowid, terms) VALUES (?, ?)", (fid, terms))
        except sqlite3.OperationalError:
            pass


