"""The code map: a bounded, rebuildable graph of a checkout's code.

``shapa map`` walks a checkout and stores, in the derived and gitignored
``<wiki>/.shapa-code.db`` (beside ``.shapa-index.db``; never in the tracked
``shapa.db``, never synced), the nodes and edges ``shapa/partition.py`` reads:

* nodes: files, and the functions/classes defined in them ("defined in" is the
  ``symbols`` table);
* edges: ``imports`` (file to file, naming the imported symbol when it is one) and
  ``calls`` (caller function to callee function, resolved through the imports);
* per file, a short ``terms`` document (path, symbol and first-docstring-line words)
  that the retrieval edges search by FTS5/BM25 and, with the ``[semantic]`` extra, by
  model2vec vectors. No source text and no constant is ever stored.

Python is read with ``ast`` (imports, defs, calls). JavaScript and TypeScript are
read with regexes (imports, exports, definitions and name-level calls): no node
dependency, so a call through a dynamic value, a re-export chain or a tsconfig path
alias is missed. Call resolution is name-level (PyCG's published recall for Python
is about 70%): an edge says "this function calls a function of that name that this
file's imports bind", never more.

Bounds, so a hostile or huge tree cannot stall or poison a session: hidden and
vendored/generated folders, nested checkouts and symlinks are never entered; a
file over :data:`MAX_FILE_BYTES`, a generated one, a non-regular one, one with a
control character in its path, and any file named like a credential are never read
or recorded; at most :data:`MAX_FILES` files; a wall-clock budget for parsing
(an interrupted build resumes where it stopped). Nothing here ever raises into a
hook: a corrupt index is deleted and rebuilt.
"""

