class _Modules:
    """Dotted-module name to file, for Python: exact by full path, else by the longest
    unique-enough suffix (``pkg.mod`` finds ``src/pkg/mod.py``)."""

    def __init__(self, paths):
        self.full: dict[str, str] = {}
        self.suffix: dict[str, list[str]] = defaultdict(list)
        for p in paths:
            mod = p[:-3].replace("/", ".")
            if mod.endswith(".__init__"):
                mod = mod[:-9]
            elif mod == "__init__":
                continue
            parts = mod.split(".")
            self.full[mod] = p
            for i in range(len(parts)):
                self.suffix[".".join(parts[i:])].append(p)

    def find(self, mod: str) -> str | None:
        if not mod:
            return None
        if mod in self.full:
            return self.full[mod]
        cands = self.suffix.get(mod)
        return min(cands, key=lambda p: (len(p), p)) if cands else None


def _js_target(files: set[str], src: str, spec: str) -> str | None:
    if spec.startswith("@/") or spec.startswith("~/"):
        bases = [f"src/{spec[2:]}", spec[2:]]
    elif spec.startswith("."):
        base = posixpath.normpath(posixpath.join(posixpath.dirname(src), spec))
        if base.startswith(".."):
            return None
        bases = [base]
    else:
        return None  # a package, a node: builtin or a tsconfig alias we do not know
    exts = (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts")
    for base in bases:
        stem, ext = posixpath.splitext(base)
        cands = [base] + [base + e for e in exts] + [base + "/index" + e for e in exts]
        if ext in (".js", ".jsx", ".mjs", ".cjs"):  # TS writes the emitted extension in imports
            cands = [stem + e for e in (".ts", ".tsx", ".mts", ".cts")] + cands
        for c in cands:
            if c in files:
                return c
    return None


def _resolve(conn) -> None:
    """Rebuild every ``edges`` row from the stored imports and calls. Calls resolve to a
    function only through what the calling file binds: an imported name or module, a
    definition in the same file, ``self.method``, or (at half weight) a method name that
    exactly one imported file defines."""
    conn.execute("DELETE FROM edges")
    path_of = {fid: p for fid, p in conn.execute("SELECT id, path FROM files")}
    fid_of = {p: f for f, p in path_of.items()}
    lang = {fid: lg for fid, lg in conn.execute("SELECT id, lang FROM files")}
    quals: dict[int, set[str]] = defaultdict(set)
    meths: dict[int, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for fid, qual, name, kind in conn.execute("SELECT fid, qual, name, kind FROM symbols"):
        quals[fid].add(qual)
        meths[fid][name].append(qual)
    pymods = _Modules([p for f, p in path_of.items() if lang[f] == "py"])
    jsfiles = {p for f, p in path_of.items() if lang[f] != "py"}
    edges: dict[tuple, float] = {}
    mod_alias: dict[int, dict[str, int]] = defaultdict(dict)
    sym_alias: dict[int, dict[str, tuple[int, str]]] = defaultdict(dict)
    imported: dict[int, set[int]] = defaultdict(set)

    def add(kind, src, dst, ssym, dsym, w):
        if src == dst and kind == "imports":
            return
        key = (kind, src, dst, ssym, dsym)
        if edges.get(key, 0.0) < w:
            edges[key] = w

    for fid, mod, name, alias, level in conn.execute("SELECT fid, mod, name, alias, level FROM imports"):
        src = path_of[fid]
        if lang[fid] == "py":
            base = ""
            if level:
                parent = src.split("/")[:-1]
                parent = parent[:len(parent) - (level - 1)] if level > 1 else parent
                base = ".".join(parent)
            dotted = ".".join(x for x in (base, mod) if x) if level else mod
            if name:
                sub = pymods.find(f"{dotted}.{name}" if dotted else name) if not level else \
                    pymods.full.get(f"{dotted}.{name}" if dotted else name)
                target = pymods.find(dotted) if not level else pymods.full.get(dotted)
                if sub and (not target or sub != target):
                    t = fid_of[sub]
                    mod_alias[fid][alias or name] = t
                    imported[fid].add(t)
                    add("imports", fid, t, "", "", 1.0)
                elif target:
                    t = fid_of[target]
                    sym_alias[fid][alias or name] = (t, name)
                    imported[fid].add(t)
                    add("imports", fid, t, "", name, 1.0)
            else:
                target = pymods.find(dotted)
                if target:
                    t = fid_of[target]
                    mod_alias[fid][alias or dotted] = t
                    if not alias and "." in dotted:
                        head = pymods.find(dotted.split(".")[0])
                        if head:
                            mod_alias[fid].setdefault(dotted.split(".")[0], fid_of[head])
                    imported[fid].add(t)
                    add("imports", fid, t, "", "", 1.0)
        else:
            target = _js_target(jsfiles, src, mod)
            if not target:
                continue
            t = fid_of[target]
            imported[fid].add(t)
            add("imports", fid, t, "", name if name not in ("*", "default") else "", 1.0)
            if name == "*":
                mod_alias[fid][alias] = t
            elif name and alias:
                sym_alias[fid][alias] = (t, name)

    for fid, caller, qual, name in conn.execute("SELECT fid, caller, qual, name FROM calls"):
        own = quals.get(fid, set())
        hit: tuple[int, str, float] | None = None
        if not qual:
            if name in sym_alias[fid]:
                t, orig = sym_alias[fid][name]
                if orig in quals.get(t, ()) or orig in ("default", "*"):
                    hit = (t, orig if orig in quals.get(t, ()) else "", 1.0)
                else:
                    hit = (t, "", 0.6)
            elif name in own:
                hit = (fid, name, 1.0)
        elif qual in ("self", "cls"):
            cls = caller.split(".")[0] if "." in caller else ""
            if cls and f"{cls}.{name}" in own:
                hit = (fid, f"{cls}.{name}", 1.0)
            elif len(meths[fid].get(name, ())) == 1:
                hit = (fid, meths[fid][name][0], 0.7)
        elif qual in mod_alias[fid]:
            t = mod_alias[fid][qual]
            hit = (t, name, 1.0) if name in quals.get(t, ()) else None
        elif qual in sym_alias[fid]:
            t, cls = sym_alias[fid][qual]
            if f"{cls}.{name}" in quals.get(t, ()):
                hit = (t, f"{cls}.{name}", 1.0)
        elif qual in own:
            if f"{qual}.{name}" in own:
                hit = (fid, f"{qual}.{name}", 1.0)
        if hit is None and qual and qual not in ("self", "cls"):
            # a method on a value we cannot type: credit the one imported file that defines it
            owners = [(t, meths[t][name][0]) for t in imported[fid]
                      if len(meths[t].get(name, ())) == 1 and "." in meths[t][name][0]]
            if len(owners) == 1:
                hit = (owners[0][0], owners[0][1], 0.5)
        if hit is not None:
            add("calls", fid, hit[0], caller, hit[1], hit[2])
    conn.executemany("INSERT INTO edges VALUES (?,?,?,?,?,?)",
                     [(k, s, d, ss, ds, w) for (k, s, d, ss, ds), w in edges.items()])


